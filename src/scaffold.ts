import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { root, selfCommand, wsDir } from "./paths";
import { shellQuote } from "./util";

/**
 * (Re)write the files that bind a Claude session to workspace `ws`.
 * Idempotent; run on every launch so the hook path tracks the installed binary.
 */
export function scaffold(ws: string) {
  const dir = wsDir(ws);
  mkdirSync(join(dir, ".claude"), { recursive: true });
  const settings = {
    env: { WS_NAME: ws, WS_ROOT: root() },
    hooks: {
      PreToolUse: [
        { matcher: "*", hooks: [{ type: "command", command: [...selfCommand(), "guard"].map(shellQuote).join(" ") }] },
      ],
    },
  };
  writeFileSync(join(dir, ".claude", "settings.json"), JSON.stringify(settings, null, 2) + "\n");
  writeFileSync(join(dir, "CLAUDE.md"), claudeMd(ws, dir));
}

const claudeMd = (ws: string, dir: string) => `# Workspace ${ws}

<!-- Generated by ws. Edits are overwritten. -->

You are bound to workspace **${ws}** (\`${dir}\`). A \`ws guard\` hook blocks
access to other workspaces and direct branch switching. Do not try to work around it.

- Each subdirectory is a git worktree of a repo. Commit, push and run tools there as normal.
- Change branch or pick up a PR only via \`ws checkout <repo> <branch>\` / \`ws checkout <repo> #<pr>\`.
  Never \`git switch\`, \`git checkout <branch>\`, or \`gh pr checkout\`.
- A branch or PR claimed by another workspace cannot be taken. If \`ws checkout\` refuses, stop and tell the user.
- After \`gh pr create\`, run \`ws pr <repo>\` to record the PR against this workspace.
- \`ws status\` shows this workspace's claims; \`ws status --all\` shows every workspace.
- \`ws release <repo>\` frees a branch when you are done with it.
`;
